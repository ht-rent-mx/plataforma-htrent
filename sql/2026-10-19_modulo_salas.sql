-- ---------------------------------------------------------------------
-- 2. Reservas
-- ---------------------------------------------------------------------
create table if not exists core.sala_reservas (
  id                 uuid primary key default gen_random_uuid(),
  serie_id           uuid,                       -- reuniones que se repiten cada semana
  sala_id            smallint not null references core.salas(id),
  titulo             text not null,
  descripcion        text,
  inicio             timestamptz not null,
  fin                timestamptz not null,
  organizador_id     uuid not null,
  organizador_nombre text,
  organizador_correo text,
  participantes      jsonb not null default '[]'::jsonb,   -- [{nombre, correo}]
  estado             text not null default 'activa',
  motivo_cancelacion text,
  cancelada_por      uuid,
  cancelada_en       timestamptz,
  outlook_evento_id  text,                       -- lo regresa Power Automate
  creado_en          timestamptz not null default now(),
  actualizado_en     timestamptz not null default now(),
  constraint sala_reservas_estado_ck  check (estado in ('activa','cancelada')),
  constraint sala_reservas_horario_ck check (fin > inicio),
  constraint sala_reservas_titulo_ck  check (length(trim(titulo)) > 0),
  -- EL CANDADO: dos reservas activas de la misma sala no pueden empalmarse
  constraint sala_reservas_sin_empalme
    exclude using gist (sala_id with =, tstzrange(inicio, fin, '[)') with &&)
    where (estado = 'activa')
);

create index if not exists sala_reservas_inicio_idx on core.sala_reservas (inicio);
create index if not exists sala_reservas_org_idx    on core.sala_reservas (organizador_id);
create index if not exists sala_reservas_serie_idx  on core.sala_reservas (serie_id);

