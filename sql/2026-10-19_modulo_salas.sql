-- Directorio para elegir participantes
create or replace function core.salas_directorio()
returns table (nombre text, correo text, puesto text)
language sql stable security definer
set search_path to 'core','public'
as $$
  select p.nombre, lower(p.correo), p.puesto
  from core.perfiles p
  where auth.uid() is not null and p.activo and p.correo is not null
  order by p.nombre
$$;

-- Reservar (con repetición semanal opcional). Regresa el id de la primera fecha.
create or replace function core.salas_reservar(
  p_sala smallint, p_titulo text, p_descripcion text,
  p_inicio timestamptz, p_fin timestamptz,
  p_participantes jsonb default '[]'::jsonb,
  p_semanas int default 1
) returns uuid
language plpgsql security definer
set search_path to 'core','public'
as $$
declare
  v_serie uuid := case when coalesce(p_semanas,1) > 1 then gen_random_uuid() end;
  v_i int; v_ini timestamptz; v_fin timestamptz; v_conf text;
  v_choques text[] := '{}'; v_nombre text; v_correo text;
  v_part jsonb; v_id uuid; v_primero uuid;
begin
  if auth.uid() is null or not core.salas_puede_reservar() then
    raise exception 'No tienes permiso para reservar salas. Pídeselo a Rogelio Morejón.';
  end if;
  if coalesce(p_semanas,1) < 1 or p_semanas > 26 then
    raise exception 'La repetición semanal va de 1 a 26 semanas';
  end if;
  perform core._salas_validar(p_sala, p_titulo, p_inicio, p_fin, true);

  select nombre, lower(correo) into v_nombre, v_correo from core.perfiles where id = auth.uid();
  v_correo := coalesce(v_correo, lower(auth.jwt()->>'email'));
  v_part := core._salas_participantes(p_participantes);

  -- primero revisa TODAS las fechas, para no dejar la serie a medias
  for v_i in 0 .. coalesce(p_semanas,1) - 1 loop
    v_ini := p_inicio + make_interval(weeks => v_i);
    v_fin := p_fin    + make_interval(weeks => v_i);
    v_conf := core._salas_conflicto(p_sala, v_ini, v_fin, null);
    if v_conf is not null then v_choques := v_choques || v_conf; end if;
  end loop;
  if array_length(v_choques, 1) > 0 then
    raise exception using errcode = 'HT409',
      message = 'La sala ya está ocupada: ' || array_to_string(v_choques, ' | ');
  end if;

  for v_i in 0 .. coalesce(p_semanas,1) - 1 loop
    insert into core.sala_reservas
      (serie_id, sala_id, titulo, descripcion, inicio, fin,
       organizador_id, organizador_nombre, organizador_correo, participantes)
    values
      (v_serie, p_sala, trim(p_titulo), nullif(trim(p_descripcion),''),
       p_inicio + make_interval(weeks => v_i), p_fin + make_interval(weeks => v_i),
       auth.uid(), v_nombre, v_correo, v_part)
    returning id into v_id;
    v_primero := coalesce(v_primero, v_id);
  end loop;
  return v_primero;
exception
  when exclusion_violation then
    raise exception using errcode = 'HT409',
      message = 'Alguien acaba de apartar esa sala en ese horario. Actualiza la agenda y elige otro.';
end $$;

-- Modificar una fecha (solo quien la reservó o un administrador)
create or replace function core.salas_modificar(
  p_id uuid, p_sala smallint, p_titulo text, p_descripcion text,
  p_inicio timestamptz, p_fin timestamptz, p_participantes jsonb default '[]'::jsonb
) returns void
language plpgsql security definer
set search_path to 'core','public'
as $$
declare r core.sala_reservas; v_conf text;
begin
  select * into r from core.sala_reservas where id = p_id;
  if not found or r.estado <> 'activa' then
    raise exception 'La reserva no existe o ya fue cancelada';
  end if;
  if r.organizador_id <> auth.uid() and not core.es_admin() then
    raise exception 'Solo quien hizo la reserva puede modificarla';
  end if;
  if r.fin < now() then
    raise exception 'Esta reunión ya terminó; no se puede modificar';
  end if;
  perform core._salas_validar(p_sala, p_titulo, p_inicio, p_fin, p_inicio <> r.inicio);

  v_conf := core._salas_conflicto(p_sala, p_inicio, p_fin, p_id);
  if v_conf is not null then
    raise exception using errcode = 'HT409', message = 'La sala ya está ocupada: ' || v_conf;
  end if;

  update core.sala_reservas
     set sala_id = p_sala, titulo = trim(p_titulo), descripcion = nullif(trim(p_descripcion),''),
         inicio = p_inicio, fin = p_fin,
         participantes = core._salas_participantes(p_participantes),
         actualizado_en = now()
   where id = p_id;
exception
  when exclusion_violation then
    raise exception using errcode = 'HT409',
      message = 'Alguien acaba de apartar esa sala en ese horario. Actualiza la agenda y elige otro.';
end $$;

-- Cancelar una fecha o la serie completa de aquí en adelante
create or replace function core.salas_cancelar(p_id uuid, p_motivo text default null, p_toda_serie boolean default false)
returns int
language plpgsql security definer
set search_path to 'core','public'
as $$
declare r core.sala_reservas; n int;
begin
  select * into r from core.sala_reservas where id = p_id;
  if not found or r.estado <> 'activa' then
    raise exception 'La reserva no existe o ya estaba cancelada';
  end if;
  if r.organizador_id <> auth.uid() and not core.es_admin() then
    raise exception 'Solo quien hizo la reserva (o un administrador) puede cancelarla';
  end if;

  update core.sala_reservas
     set estado = 'cancelada', motivo_cancelacion = nullif(trim(p_motivo),''),
         cancelada_por = auth.uid(), cancelada_en = now(), actualizado_en = now()
   where estado = 'activa'
     and (id = p_id
          or (p_toda_serie and r.serie_id is not null and serie_id = r.serie_id and inicio >= r.inicio));
  get diagnostics n = row_count;
  return n;
end $$;

-- Power Automate devuelve aquí el id del evento de Outlook creado
create or replace function core.salas_registrar_evento(p_id uuid, p_evento text, p_secreto text)
returns void
language plpgsql security definer
set search_path to 'core','public'
as $$
begin
  if p_secreto is null or p_secreto <> (select valor from core.salas_config where clave = 'secreto_flujo') then
    raise exception 'No autorizado';
  end if;
  update core.sala_reservas set outlook_evento_id = nullif(trim(p_evento),'') where id = p_id;
end $$;

