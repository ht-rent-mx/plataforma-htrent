create or replace function core.salas_puede_reservar()
returns boolean language sql stable security definer
set search_path to 'core','public'
as $$ select core.es_admin() or coalesce(core.puede_escribir('salas'), false) $$;

create or replace function core._salas_hora(t timestamptz)
returns text language sql immutable
as $$ select to_char(t at time zone 'America/Mexico_City', 'HH24:MI') $$;

create or replace function core._salas_dia(t timestamptz)
returns text language sql immutable
as $$ select to_char(t at time zone 'America/Mexico_City', 'DD/MM/YYYY') $$;

-- Regresa null si la sala está libre, o un texto con quién la tiene
create or replace function core._salas_conflicto(p_sala smallint, p_ini timestamptz, p_fin timestamptz, p_excluir uuid)
returns text language sql stable security definer
set search_path to 'core','public'
as $$
  select string_agg(
           format('%s de %s a %s, apartada por %s ("%s")',
                  core._salas_dia(r.inicio), core._salas_hora(r.inicio), core._salas_hora(r.fin),
                  coalesce(r.organizador_nombre, r.organizador_correo, 'otra persona'), r.titulo),
           '; ' order by r.inicio)
  from core.sala_reservas r
  where r.sala_id = p_sala
    and r.estado = 'activa'
    and (p_excluir is null or r.id <> p_excluir)
    and tstzrange(r.inicio, r.fin, '[)') && tstzrange(p_ini, p_fin, '[)')
$$;

-- Limpia la lista de participantes: correos válidos, sin repetir, máx. 80
create or replace function core._salas_participantes(p jsonb)
returns jsonb language sql immutable
as $$
  select coalesce(jsonb_agg(jsonb_build_object('nombre', nombre, 'correo', correo) order by orden), '[]'::jsonb)
  from (
    select distinct on (correo) correo, nombre, orden
    from (
      select lower(trim(x->>'correo')) as correo,
             nullif(trim(x->>'nombre'), '') as nombre,
             ord as orden
      from jsonb_array_elements(case when jsonb_typeof(p) = 'array' then p else '[]'::jsonb end)
           with ordinality as t(x, ord)
    ) a
    where correo ~ '^[^@\s;,]+@[^@\s;,]+\.[^@\s;,]+$'
    order by correo, orden
    limit 80
  ) b
$$;

create or replace function core._salas_validar(p_sala smallint, p_titulo text, p_ini timestamptz, p_fin timestamptz, p_es_nueva boolean)
returns void language plpgsql stable security definer
set search_path to 'core','public'
as $$
begin
  if p_titulo is null or length(trim(p_titulo)) = 0 then
    raise exception 'Escribe el tema de la reunión';
  end if;
  if not exists (select 1 from core.salas where id = p_sala and activa) then
    raise exception 'La sala elegida no existe o no está disponible';
  end if;
  if p_ini is null or p_fin is null or p_fin <= p_ini then
    raise exception 'La hora de término debe ser posterior a la de inicio';
  end if;
  if p_fin - p_ini > interval '10 hours' then
    raise exception 'Una reserva no puede durar más de 10 horas';
  end if;
  if (p_ini at time zone 'America/Mexico_City')::date <> ((p_fin - interval '1 second') at time zone 'America/Mexico_City')::date then
    raise exception 'La reunión debe empezar y terminar el mismo día';
  end if;
  if p_es_nueva and p_ini < now() - interval '15 minutes' then
    raise exception 'No se puede reservar en un horario que ya pasó';
  end if;
end $$;

