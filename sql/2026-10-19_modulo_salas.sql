-- Plataforma HT · Módulo Salas de juntas (2026-10-19)
--
-- Qué hace:
--   1. Catálogo de salas: Plataforma, Caja Seca y Portacontenedor.
--   2. Reservas con BLOQUEO REAL: la base de datos rechaza cualquier
--      reserva que se empalme con otra activa en la misma sala
--      (restricción EXCLUDE), aunque dos personas guarden al mismo tiempo.
--   3. Cada reserva nueva, modificada o cancelada avisa a un flujo de
--      Power Automate, que manda la invitación de Outlook a los
--      participantes (o la cancelación).
--
-- Cómo correrlo: Supabase > SQL Editor > pegar todo > Run.
-- Se puede correr más de una vez sin dañar nada.
-- =====================================================================

